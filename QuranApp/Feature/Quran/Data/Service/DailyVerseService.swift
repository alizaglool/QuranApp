    static func verseForToday() -> DailyVerse {
        let hijri = Calendar(identifier: .islamicUmmAlQura)
        let comps = hijri.dateComponents([.year, .month, .day], from: Date())
        let year  = comps.year  ?? 1446
        let month = comps.month ?? 1
        let day   = comps.day   ?? 1

        // Splitmix64 hash → uniform distribution across 6236 verses
        var s = UInt64(year) &* 10000 &+ UInt64(month) &* 100 &+ UInt64(day)
        s ^= s >> 17;  s &*= 0xbf58476d1ce4e5b9
        s ^= s >> 31;  s &*= 0x94d049bb133111eb
        s ^= s >> 32

        return verse(at: Int(s % 6236))
    }

    private static func verse(at flatIndex: Int) -> DailyVerse {
        var remaining = flatIndex
        for (idx, count) in verseCount.enumerated() {
            if remaining < count {
                let surah    = idx + 1
                let verseNum = remaining + 1
                let name     = surahNames[surah] ?? "سورة \(surah)"
                return DailyVerse(surah: surah, verse: verseNum, ref: "\(name): \(verseNum.arabicNumerals)")
            }
            remaining -= count
        }
        return DailyVerse(surah: 1, verse: 1, ref: "الفاتحة: ١")
    }

